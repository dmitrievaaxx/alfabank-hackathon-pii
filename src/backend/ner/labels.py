def normalize_label(cat: str) -> str:
    for ch in " /(),.":
        cat = cat.replace(ch, "_")
    while "__" in cat:
        cat = cat.replace("__", "_")
    return cat.strip("_")


# Словари перекодировки: категория <-> нормализованное имя метки
cat2norm: dict[str, str] = {cat: normalize_label(cat) for cat in CATEGORIES}
norm2cat: dict[str, str] = {norm: cat for cat, norm in cat2norm.items()}

# Полный список меток: O + B-/I- для каждой категории → итого 61 метка
labels: list[str] = ["O"] + [
    f"{bio}-{normalize_label(cat)}"
    for cat in CATEGORIES
    for bio in ("B", "I")
]

label2id: dict[str, int] = {lbl: i for i, lbl in enumerate(labels)}
id2label: dict[int, str] = {i: lbl for i, lbl in enumerate(labels)}
